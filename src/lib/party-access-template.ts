export const PARTY_ACCESS_URL_PLACEHOLDER = '{계정 접근 토큰 생성 주소}';

export function buildPartyAccessDeliveryTemplate(accessUrl = PARTY_ACCESS_URL_PLACEHOLDER): string {
  const url = String(accessUrl || PARTY_ACCESS_URL_PLACEHOLDER).trim() || PARTY_ACCESS_URL_PLACEHOLDER;
  return `✅ 아래 내용 꼭 읽어주세요! 로그인 관련 내용입니다!! ✅

✅ 계정 업데이트 주소 : ${url} ✅

이용하시기 전 꼭 하셔야 하는 2 STEP

1️⃣ 계정 업데이트 주소(위에 주소) 들어가셔서 필수 동의 3가지 입력 및 만드셔야 하는 프로필 확인

2️⃣ 동의를 완료한 뒤 나오는 최신 계정 정보 확인 및
이메일 인증 필요시 핀번호 확인 후 이메일 접근 링크 버튼 누르고 핀번호 입력하고 인증 받기

⚠️ 계정 정보, 비밀번호, 추가회원 자리 기능은 절대 수정하지 마세요. 수정이 확인되면 이용 제한 및 관련 조치가 진행될 수 있습니다. ⚠️

⚠️ 계정 업데이트 주소에 나오는 프로필 이름으로 안 만드시면, 일주일 단위로 프로필 정리 시 해당 프로필 삭제됩니다! 꼭 정해진 프로필 이름으로 만들어주세요! ⚠️

계정 업데이트 주소는 다른 파티원들이 파티 탈퇴 등으로 계정 정보를 변경해야 할 때마다 실시간으로 업데이트 되는 주소입니다.

프로필이 꽉 찼다면 계정 접근 주소에서 파티원 프로필 현황에 없는 프로필 삭제 후 새로 만드셔서 사용하시면 됩니다!

로그인이 안될 때마다 직접 묻지 마시고 먼저 저 링크에서 업데이트 된 정보 확인 후 재 로그인 시도해주세요.

이메일 인증은 업데이트 주소 안에 적힌 핀번호를 이용해서 접근하실 수 있으십니다.

기타 문의사항은 연락 주시면 감사하겠습니다.`;
}
